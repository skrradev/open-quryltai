# fold Kazakh letters and common RU/KK transliteration variants to a common form
FOLD = str.maketrans({
 'ә':'а','ғ':'г','қ':'к','ң':'н','ө':'о','ұ':'у','ү':'у','һ':'х','і':'и','ё':'е',
})
def norm(s):
    s = s.lower().translate(FOLD)
    s = re.sub(r'[^а-я]', '', s)
    return s

def name_keys(surname, given):
    """Return (full, surname, given-first-token) normalised."""
    g = given.split()
    return norm(surname), norm(' '.join(g)), norm(g[0] if g else '')

sql = open('backend/src/main/resources/db/migration/V3__create_candidate.sql').read()
cands = []
for m in re.finditer(r"\('([a-z_]+)', (\d+), '((?:[^']|'')*)', '((?:[^']|'')*)', (\d+), '([MF])', '((?:[^']|'')*)'", sql):
    cands.append(dict(party=m.group(1), order=int(m.group(2)), surname=m.group(3),
                      given=m.group(4), year=m.group(5), sex=m.group(6), pos=m.group(7)))
print(f"candidates parsed: {len(cands)}  senators: {len(SEN)}")

# existing photo coverage
have = set()
for f, c in [("data/work/parliament_incumbent_profiles.tsv","primary_public_photo_url"),
             ("data/work/parliament_primary_photo_promotions.tsv","primary_public_photo_url"),
             ("data/work/verified_candidate_biographies.tsv","public_photo_url"),
             ("data/work/senate_incumbent_profiles.tsv","photo_source_url")]:
    for x in csv.DictReader(open(f), delimiter='\t'):
        if (x.get(c) or '').strip(): have.add((x['party_id'], int(x['list_order'])))
import glob
for f in glob.glob("data/work/*_candidate_profiles.tsv"):
    h = next(csv.reader(open(f), delimiter='\t'))
    if 'photo_source_url' not in h: continue
    for x in csv.DictReader(open(f), delimiter='\t'):
        if (x.get('photo_source_url') or '').strip(): have.add((x['party_id'], int(x['list_order'])))

exact, surname_only = [], []
for bid, h, sname, spos in SEN:
    parts = sname.split()
    s_sur, s_giv = parts[0], ' '.join(parts[1:])
    ns_sur, ns_giv, ns_first = name_keys(s_sur, s_giv) if s_giv else (norm(s_sur), '', '')
    for c in cands:
        nc_sur, nc_giv, nc_first = name_keys(c['surname'], c['given'])
        if nc_sur != ns_sur:
            continue
        rec = dict(senator=sname, senate_pos=spos, blog=bid, hash=h,
                   party=c['party'], order=c['order'],
                   candidate=f"{c['surname']} {c['given']}", year=c['year'], sex=c['sex'],
                   cand_pos=c['pos'], has_photo=(c['party'], c['order']) in have)
        if nc_giv == ns_giv and ns_giv:
            exact.append(rec)
        elif nc_first == ns_first and ns_first:
            rec['note'] = 'surname+first name match, patronymic differs'
            exact.append(rec)
        else:
            surname_only.append(rec)

print(f"\n=== EXACT / near-exact name matches: {len(exact)} ===")
for r in sorted(exact, key=lambda r: (r['party'], r['order'])):
    flag = 'HAS PHOTO' if r['has_photo'] else 'NO PHOTO -> NEW'
    print(f"{r['party']:11} {r['order']:4}  {r['candidate']:42} {r['year']} {r['sex']}  [{flag}]")
    print(f"{'':16}  senate: {r['senator']}  ({r['senate_pos'][:60]})")
    print(f"{'':16}  cand pos: {r['cand_pos'][:80]}")
    if r.get('note'): print(f"{'':16}  !! {r['note']}")

print(f"\n=== surname-only collisions (NOT matches, review): {len(surname_only)} ===")
for r in sorted(surname_only, key=lambda r: (r['party'], r['order'])):
    print(f"{r['party']:11} {r['order']:4}  {r['candidate']:42} {r['year']} {r['sex']}  vs senate {r['senator']}")
    print(f"{'':16}  cand pos: {r['cand_pos'][:80]}")
