def compute_hash(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def generate_verified_sql():
    portable_sql = [
        "-- V13__seed_candidate_ai_overviews.sql",
        "-- Seed ONLY strictly verified Google-style AI Overview sections for public figures found in Google Search & Wikipedia.",
        "",
        "-- Step 1: Clean up any obsolete unverified overview entries",
        "DELETE FROM candidate_content WHERE section_type = 'OVERVIEW';",
        "",
        "-- Step 2: Insert verified bilingual AI Overviews",
    ]

    count = 0
    for (party_id, order), lang_data in VERIFIED_AI_OVERVIEWS.items():
        for lang in ("ru", "kk"):
            entry = lang_data[lang]
            title = entry["title"].replace("'", "''")
            body = entry["body"].replace("'", "''")
            chash = compute_hash(entry["body"])
            portable_sql.append(
                f"INSERT INTO candidate_content (candidate_id, language, section_type, title, body_markdown, sort_order, review_status, reviewed_at, content_hash, source_revision, active)\n"
                f"SELECT c.candidate_id, '{lang}', 'OVERVIEW', '{title}', '{body}', 0, 'PUBLISHED', CURRENT_TIMESTAMP, '{chash}', 'google_ai_overview_verified', TRUE\n"
                f"FROM candidate c\n"
                f"WHERE c.party_id = '{party_id}' AND c.list_order = {order};\n"
            )
            count += 1

    with open(SQL_OUTPUT, "w", encoding="utf-8") as f:
        f.write("\n".join(portable_sql))

    print(f"Generated {SQL_OUTPUT} with {len(VERIFIED_AI_OVERVIEWS)} verified candidate AI Overviews ({count} records).")


if __name__ == "__main__":
    generate_verified_sql()
